def detect(text: str) -> tuple:
    import re
    low = (text or "").lower()
    best, score = None, 0
    for key, data in INDUSTRIES.items():
        s = sum(1 for m in data["match"] if re.search(r"\b" + re.escape(m.strip()) + r"s?\b", low))
        if s > score:
            best, score = key, s
    return (best, INDUSTRIES[best]) if best else ("generic", GENERIC)

